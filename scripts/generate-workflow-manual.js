#!/usr/bin/env node
/**
 * generate-workflow-manual — MT-007 graceful degradation
 *
 *   node scripts/generate-workflow-manual.js --check     manual/ matches core/ and core/capabilities.json
 *   node scripts/generate-workflow-manual.js --write     regenerate manual/ from core/
 *
 * ทำไมต้องมี: workflow ใน core/ ถูกเขียนให้ Claude Code ใช้ความสามารถที่เครื่องมืออื่นอาจไม่มี —
 * slash-command argument, คำสั่งที่รันให้ก่อนอ่าน, subagent, /code-review ในตัว, rule ที่โหลดตาม path,
 * hook ที่บล็อกระหว่าง session · เครื่องมือที่ไม่มีสิ่งเหล่านี้ (หรือคนที่ทำตามเอง) ต้องทำงานเดิมได้แบบ
 * manual/serial โดยไม่ต้องเดาว่าอะไรหายไป
 *
 * ไฟล์นี้ render core/skills และ core/agents เป็น playbook ธรรมดาใน manual/ ที่อ่านแล้วทำตามได้ทีละขั้น
 * แล้วแนบ "ทำแทนยังไง" เฉพาะความสามารถที่ skill นั้นใช้จริง (ตรวจจากเนื้อหาด้วย regex ใน
 * core/capabilities.json) · manual/README.md บอกด้วยว่า **การรับประกันไหนยังอยู่** เมื่อไม่มี session
 * features และไหนหายไป — ข้อที่หายต้องพูดตรง ๆ ไม่ใช่ปล่อยให้เข้าใจว่ายังมี
 *
 * นี่ไม่ใช่ adapter ของ vendor ใดวendor หนึ่ง (D-006: ไม่ทำ Codex/Copilot จนกว่าผู้ใช้สั่ง) — มันคือ
 * ชั้นล่างสุดที่ทุกเครื่องมือตกลงมาได้ และเป็น Markdown ธรรมดาที่ไม่ต้องมี runtime อะไรเลย
 *
 * exit 0 = ผ่าน | exit 1 = capability ที่ core ใช้ไม่มีในแผนที่ หรือ manual/ ไม่ตรงกับ core (--check)
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { loadCoreSkills } = require('./generate-workflow-skills.js');
const { loadCoreAgents } = require('./generate-workflow-agents.js');

const REPO_ROOT = path.resolve(__dirname, '..');
const HEADER = '<!-- generated by scripts/generate-workflow-manual.js from core/ — do not edit by hand -->';

function loadCapabilities(root) {
  const map = JSON.parse(fs.readFileSync(path.join(root, 'core', 'capabilities.json'), 'utf8'));
  return { ...map, capabilities: map.capabilities.map((c) => ({ ...c, regex: new RegExp(c.detect, 'm') })) };
}

function uses(capabilities, text) {
  return capabilities.filter((c) => c.regex.test(text));
}

function renderSkill(skill, capabilities) {
  const shell = [...skill.body.matchAll(/^\{\{shell:\s*(.+)\}\}$/gm)].map((m) => m[1]);
  const body = skill.body
    .replace(/\{\{ARGUMENTS\}\}/g, '<argument>')
    .replace(/^\{\{shell:\s*(.+)\}\}$/gm, 'Run first: `$1`');
  const needed = uses(capabilities, `${skill.body}\n${skill.claudeAllowedTools.join(' ')}`);
  const lines = [
    HEADER,
    `# ${skill.id} — manual playbook`,
    '',
    `> ${skill.description}`,
    `> Argument: \`${skill.argumentHint}\``,
    skill.invocation === 'human' ? '> Start this only when a person explicitly asks for it — its side effects are hard to undo.' : null,
    '',
  ].filter((line) => line !== null);
  if (shell.length) {
    lines.push('## Run first', '', ...shell.map((cmd) => `- \`${cmd}\``), '');
  }
  lines.push('## Steps', '', body.trimEnd(), '');
  if (needed.length) {
    lines.push('## Without these tool features', '');
    for (const c of needed) lines.push(`- **${c.id}** — ${c.without}`);
    lines.push('');
  }
  return `${lines.join('\n')}`;
}

function renderAgent(agent, capabilities) {
  const needed = uses(capabilities, `modelTier: ${agent.modelTier}\n${agent.body}`);
  const lines = [
    HEADER,
    `# ${agent.id} — delegated role, done serially`,
    '',
    `> ${agent.description}`,
    '> When a playbook delegates to this role and your tool has no subagents, do it yourself in the same session, reading only what this file lists.',
    '',
    agent.body.trimEnd(),
    '',
  ];
  if (needed.length) {
    lines.push('## Without these tool features', '');
    for (const c of needed) lines.push(`- **${c.id}** — ${c.without}`);
    lines.push('');
  }
  return lines.join('\n');
}

function renderIndex(skills, agents, map) {
  const lines = [
    HEADER,
    '# Manual playbooks — the workflow without tool-specific features',
    '',
    'Every playbook here is rendered from the same `core/` that produces the Claude Code skills, so it cannot drift from them.',
    'Use it when your AI tool has no slash commands, subagents, inline commands or hooks — or when a person follows the workflow by hand.',
    '',
    '## Playbooks',
    '',
    '| Step | Playbook | Needs a person to start it |',
    '|---|---|---|',
    ...skills.map((s) => `| ${s.description.split('.')[0]} | [${s.id}](skills/${s.id}.md) | ${s.invocation === 'human' ? 'yes' : 'no'} |`),
    '',
    'Delegated roles: ' + agents.map((a) => `[${a.id}](agents/${a.id}.md)`).join(' · '),
    '',
    '## What still holds without session features',
    '',
    'Hooks only exist inside a session of a tool that supports them. The gate (`node .claude/gate.js`, run by the pre-push hook and CI) is the same rules enforced outside any session. This table says which guarantees survive when there is no session tooling at all.',
    '',
    '| Guarantee | Enforced by | Holds without session features | What that means |',
    '|---|---|:---:|---|',
    ...map.guarantees.map((g) => `| ${g.id} | ${g.enforcedBy} | ${g.holdsWithoutSession ? 'yes' : '**no**'} | ${g.note} |`),
    '',
  ];
  return lines.join('\n');
}

function build(root) {
  const map = loadCapabilities(root);
  const skills = loadCoreSkills(root);
  const agents = loadCoreAgents(root);
  const outputs = [
    { targetPath: path.join('manual', 'README.md'), generated: renderIndex(skills, agents, map) },
    ...skills.map((s) => ({ targetPath: path.join('manual', 'skills', `${s.id}.md`), generated: renderSkill(s, map.capabilities) })),
    ...agents.map((a) => ({ targetPath: path.join('manual', 'agents', `${a.id}.md`), generated: renderAgent(a, map.capabilities) })),
  ];

  // Anything in core that looks like a tool feature but is not in the map would render with no
  // fallback, which is exactly the silent gap this layer exists to prevent.
  const problems = [];
  const corpus = [...skills.map((s) => `${s.body}\n${s.claudeAllowedTools.join(' ')}`), ...agents.map((a) => `modelTier: ${a.modelTier}\n${a.body}`)].join('\n');
  const unknownFeatures = [
    [/\{\{[a-zA-Z]+[:}]/g, (m) => !/^\{\{(ARGUMENTS|shell)/.test(m)],
  ];
  for (const [regex, isUnknown] of unknownFeatures) {
    for (const m of corpus.match(regex) || []) if (isUnknown(m)) problems.push(`core uses placeholder ${m} that has no fallback in core/capabilities.json`);
  }
  for (const c of map.capabilities) {
    if (!c.regex.test(corpus)) problems.push(`capability "${c.id}" is mapped but nothing in core uses it — remove it or fix its detect pattern`);
  }
  return { outputs, problems: [...new Set(problems)] };
}

function main(argv = process.argv.slice(2)) {
  const write = argv.includes('--write');
  const rootIndex = argv.indexOf('--root');
  const root = path.resolve(rootIndex !== -1 ? argv[rootIndex + 1] : REPO_ROOT);
  let result;
  try { result = build(root); } catch (error) {
    console.error(`generate-workflow-manual: ${error.message}`);
    return 1;
  }
  if (result.problems.length) {
    console.error(`generate-workflow-manual: FAIL (${result.problems.length})`);
    for (const problem of result.problems) console.error(`  - ${problem}`);
    return 1;
  }
  if (write) {
    fs.rmSync(path.join(root, 'manual'), { recursive: true, force: true });
    for (const output of result.outputs) {
      const file = path.join(root, output.targetPath);
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, output.generated);
    }
    console.log(`✓ generate-workflow-manual: wrote ${result.outputs.length} file(s) under manual/`);
    return 0;
  }
  const expected = new Set(result.outputs.map((o) => o.targetPath.replace(/\\/g, '/')));
  const problems = [];
  for (const output of result.outputs) {
    const file = path.join(root, output.targetPath);
    if (!fs.existsSync(file)) problems.push(`${output.targetPath}: missing (run --write)`);
    else if (fs.readFileSync(file, 'utf8') !== output.generated) problems.push(`${output.targetPath}: out of sync with core/ (run --write)`);
  }
  const walk = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)])) : []);
  for (const file of walk(path.join(root, 'manual'))) {
    const rel = path.relative(root, file).replace(/\\/g, '/');
    if (!expected.has(rel)) problems.push(`${rel}: not generated from core/ (hand-added playbooks bypass the core)`);
  }
  if (problems.length) {
    console.error(`generate-workflow-manual: FAIL (${problems.length})`);
    for (const problem of problems) console.error(`  - ${problem}`);
    return 1;
  }
  console.log(`✓ generate-workflow-manual --check: ${result.outputs.length} playbook file(s) match core/`);
  return 0;
}

if (require.main === module) process.exit(main());

module.exports = { build, loadCapabilities, renderAgent, renderSkill };
