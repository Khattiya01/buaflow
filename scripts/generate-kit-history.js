#!/usr/bin/env node
/**
 * generate-kit-history — every version of every file the kit installs, by sha256 (PE-011)
 *
 *   node scripts/generate-kit-history.js --write    add this repository's git history and working tree to the manifest
 *   node scripts/generate-kit-history.js --check    every file the kit installs today is in the manifest
 *
 * ทำไมต้องมี: `install` และ `lock` แยก "ไฟล์ของ kit รุ่นเก่า" (ทับได้) ออกจาก "ไฟล์ที่ทีมแก้เอง" (conflict) ·
 * โปรเจกต์ที่มี lock ใช้ hash ใน lock ได้ แต่โปรเจกต์ที่ติดตั้งก่อน 3.11 ไม่มี lock และทางเดียวที่เหลือคือ
 * `git log` ในโฟลเดอร์ของ kit — ซึ่ง kit ที่มากับ plugin (อยู่ใน ~/.claude/plugins/cache/) ไม่ใช่ git checkout
 * ⇒ ไฟล์ kit เก่าทุกไฟล์ขึ้นเป็น conflict ทั้งที่ไม่มีใครแก้ · manifest นี้คือประวัตินั้น ติดไปกับ kit เลย
 *
 * manifest เพิ่มอย่างเดียว ไม่เคยลบ: CI checkout แบบ shallow จึงไม่ทำให้ประวัติหาย · --check ตรวจแค่ว่าเนื้อหา
 * ปัจจุบันของทุกไฟล์อยู่ในนั้น ⇒ แก้ไฟล์ที่ kit ติดตั้งแล้วต้องรัน --write (เหมือน CHECKSUMS ของ plugin)
 *
 * exit 0 = ตรง · exit 1 = ขาด / ผิดรูปแบบ
 */
'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..');
const MANIFEST = path.join('claude-setup', 'kit-history.json');

const hash = (text) => crypto.createHash('sha256').update(text.replace(/\r\n/g, '\n')).digest('hex');

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
}

// The same files install.js treats as controls, in either mode: whatever a project may hold a copy of.
function sources(root) {
  const { KIT_ONLY } = require(path.join(root, 'claude-setup', 'install.js'));
  const setup = path.join(root, 'claude-setup');
  const files = [
    ...fs.readdirSync(setup).filter((n) => n.endsWith('.js') && !KIT_ONLY.has(n)).map((n) => path.join(setup, n)),
    ...walk(path.join(setup, 'hooks')).filter((f) => f.endsWith('.js')),
    ...walk(path.join(setup, 'agents')).filter((f) => f.endsWith('.md') && path.basename(f) !== 'README.md'),
    ...walk(path.join(setup, 'skills')),
    ...walk(path.join(root, 'standards', 'control-sets')),
  ];
  return files.map((f) => path.relative(root, f).replace(/\\/g, '/')).sort();
}

function read(root) {
  try { return JSON.parse(fs.readFileSync(path.join(root, MANIFEST), 'utf8')); } catch { return null; }
}

const git = (root, args) => spawnSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

// The kit version current when a commit was made: package.json, or the newest heading of VERSION.md
// before package.json existed. Content first seen at X shipped in X or in the release after it.
function versionAt(root, commit, cache) {
  if (cache.has(commit)) return cache.get(commit);
  let version = null;
  const pkg = git(root, ['show', `${commit}:package.json`]);
  if (pkg.status === 0) { try { version = JSON.parse(pkg.stdout).version || null; } catch { /* not JSON at that commit */ } }
  if (!version) {
    const log = git(root, ['show', `${commit}:VERSION.md`]);
    version = log.status === 0 ? (log.stdout.match(/^## v(\d+\.\d+(?:\.\d+)?)/m) || [])[1] || null : null;
  }
  cache.set(commit, version);
  return version;
}

function build(root) {
  const current = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
  const previous = read(root)?.files || {};
  const cache = new Map();
  const files = {};
  for (const rel of sources(root)) {
    const seen = { ...(previous[rel] || {}) };
    // Oldest first, so a content that came back later keeps the version it first shipped in.
    const log = git(root, ['log', '--reverse', '--format=%H', '--', rel]);
    for (const commit of log.status === 0 ? log.stdout.split(/\r?\n/).filter(Boolean) : []) {
      const show = git(root, ['show', `${commit}:${rel}`]);
      if (show.status !== 0) continue;
      const digest = hash(show.stdout);
      if (!(digest in seen)) seen[digest] = versionAt(root, commit, cache) || 'unknown';
    }
    const now = hash(fs.readFileSync(path.join(root, rel), 'utf8'));
    if (!(now in seen)) seen[now] = current;
    files[rel] = seen;
  }
  // Files the kit no longer ships stay: a project may still hold one, and its history still says whose it is.
  for (const [rel, seen] of Object.entries(previous)) if (!files[rel]) files[rel] = seen;
  return {
    _: 'Generated by scripts/generate-kit-history.js (PE-011). Every content of every file the kit installs into .claude/, by sha256 of its LF text, with the kit version current when it was first committed. install and lock read it to tell an old kit file from a project\'s own change when there is no lock and the kit is not a git checkout (the plugin cache). Append-only.',
    schemaVersion: '1.0',
    files: Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b))),
  };
}

function check(root) {
  const manifest = read(root);
  if (!manifest || manifest.schemaVersion !== '1.0' || typeof manifest.files !== 'object') return [`${MANIFEST} is missing or not schemaVersion 1.0`];
  const missing = [];
  for (const rel of sources(root)) {
    if (!manifest.files[rel]?.[hash(fs.readFileSync(path.join(root, rel), 'utf8'))]) missing.push(rel);
  }
  return missing.map((rel) => `${rel}: its current content is not in ${MANIFEST}`);
}

function main(argv = process.argv.slice(2)) {
  if (argv.includes('--write')) {
    const manifest = build(ROOT);
    fs.writeFileSync(path.join(ROOT, MANIFEST), `${JSON.stringify(manifest, null, 2)}\n`);
    const versions = Object.values(manifest.files).reduce((n, seen) => n + Object.keys(seen).length, 0);
    console.log(`kit history: ${Object.keys(manifest.files).length} file(s), ${versions} version(s) → ${MANIFEST}`);
    return 0;
  }
  const problems = check(ROOT);
  if (problems.length) {
    for (const p of problems) console.error(`kit history: ${p}`);
    console.error('kit history: FAIL — run node scripts/generate-kit-history.js --write');
    return 1;
  }
  console.log('kit history: PASS (every installed file\'s current content is recorded)');
  return 0;
}

if (require.main === module) process.exit(main());

module.exports = { build, check, sources };
